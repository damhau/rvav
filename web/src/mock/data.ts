function vm(name: string, env: string, over: Partial<VM> = {}): VM {
  seq += 17;
  const net = networks.find((n) => n.env === env) ?? networks[0];
  const host = 20 + (seq % 200);
  return {
    moref: `vm-${seq}`,
    name,
    fqdn: `${name}.${DOMAIN}`,
    ip: `${net.subnet.split(".").slice(0, 3).join(".")}.${host}`,
    power: "on",
    os: "Red Hat Enterprise Linux 9.4",
    vcpu: 4,
    ramGB: 16,
    diskGB: 80,
    cluster: env === "prd" ? "GVA-PRD-CL01" : env === "tst" ? "GVA-TST-CL01" : "GVA-DEV-CL01",
    datastore: env === "prd" ? "vsan-gva-prd-cl01" : env === "tst" ? "vsan-gva-tst-cl01" : "vsan-gva-dev-cl01",
    network: net.name,
    template: "tpl-rhel9.4-2026.10",
    tools: "running",
    cpuPct: 8 + (seq % 50),
    memPct: 30 + (seq % 45),
    snapshots: [],
    ...over,
  };
}

